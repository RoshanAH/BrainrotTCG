/**
 * Writes src/content/sets/<set>/PROMPTS.md: copy-paste prompts for making a set's
 * art for free in the Gemini app (one setup message, then one message per card),
 * listing which cards still need a real image.
 *
 * Usage: npm run prompts [-- <set-id>]
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { validateSet, type SetDefinition } from '../../src/engine/index.ts';
import { findArt, SETS_DIR } from './lib.ts';

const SETUP = `You're the illustrator for a meme trading card game. I'll send card briefs one at a time. For each one, generate ONE image:
- Match the rendering style of the attached card's artwork: vivid, glossy, high-detail, slightly surreal meme realism, dramatic lighting, saturated colors
- Illustration only: NO card frame, NO border, NO text, letters, numbers or logos
- Portrait 6:7, subject centered and fully visible, keep the edges free of important detail
- No real or recognizable people
Reply "ready" and wait for the first brief.`;

/** Art briefs were written for flat SVG art; drop the palette/outline notes so Gemini keeps its glossy style. */
const forGemini = (brief: string) =>
  brief
    .replace(/\s*Colou?rs?:[^.]*\.?/gi, '')
    .replace(/\b(flat[- ]vector|flat|vector|thick outlines?|bold outlines?|charcoal outlines?)\b\s*/gi, '')
    .replace(/\s{2,}/g, ' ')
    .trim();

const sheet = (set: SetDefinition) => {
  const rows = set.cards.map((card) => {
    const art = findArt(set.id, card.id);
    const status = art?.kind === 'raster' || art?.kind === 'full' ? '✅ real image' : art?.kind === 'svg' ? '🟡 placeholder' : '❌ missing';
    return { card, status };
  });
  const todo = rows.filter((r) => !r.status.startsWith('✅'));
  return `# ${set.name} (${set.era}): art prompts

Generated by \`npm run prompts\`. ${todo.length === 0 ? 'Every card has a real image. 🎉' : `**${todo.length} of ${set.cards.length} cards still need a real image.**`}

## How to use (free, Gemini app)

1. Open a new chat at gemini.google.com and attach \`src/content/sets/genesis/art/tralalero-tralala.card.png\` as the style reference.
2. Paste the setup message, then send each card message on its own.
3. Save each image as \`src/content/sets/${set.id}/art/<card-id>.png\`, then run \`npm run cards\`.
   The frame, title and caption are added by code, so the image should have **no text**.

### Setup message

\`\`\`
${SETUP}
\`\`\`

## Cards

| Card id | Name | Rarity | Art |
| --- | --- | --- | --- |
${rows.map(({ card, status }) => `| \`${card.id}\` | ${card.name} | ${card.rarity} | ${status} |`).join('\n')}

${rows
  .map(
    ({ card, status }) => `### ${card.name} (\`${card.id}.png\`) ${status}

\`\`\`
Card: ${card.name}${card.year ? ` (${card.year})` : ''}. ${card.art ? forGemini(card.art) : `${card.name}: ${card.flavor ?? card.caption ?? ''}`}
\`\`\``,
  )
  .join('\n\n')}
`;
};

const only = process.argv[2];
const ids = readdirSync(SETS_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(`${SETS_DIR}/${d.name}/set.json`))
  .map((d) => d.name)
  .filter((id) => id !== 'genesis' && (!only || id === only));

for (const id of ids) {
  const set = validateSet(JSON.parse(readFileSync(`${SETS_DIR}/${id}/set.json`, 'utf8')));
  writeFileSync(`${SETS_DIR}/${id}/PROMPTS.md`, sheet(set));
  console.log(`wrote src/content/sets/${id}/PROMPTS.md`);
}
